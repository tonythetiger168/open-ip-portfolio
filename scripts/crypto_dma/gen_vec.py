"""Generate tb/Crypto_DMA_vec.svh: random AES-GCM messages for the Crypto_DMA
core testbench, with the expected output text and tag from the Python
`cryptography` package (OpenSSL), an implementation independent of the RTL.

  python3 scripts/crypto_dma/gen_vec.py [N] [SEED]

Each case: key size, direction, AAD length, text length, key, IV, AAD and
input text bytes, expected output bytes and tag. Decrypt cases carry the
correct tag, a truncated tag (TAG_LEN 4..15) or a corrupted one (TAG_OK 0).
"""
import os, random, sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
N = int(sys.argv[1]) if len(sys.argv) > 1 else 48
rng = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 2026)

def gcm(key, iv, aad, pt):
    e = Cipher(algorithms.AES(key), modes.GCM(iv)).encryptor()
    e.authenticate_additional_data(aad)
    ct = e.update(pt) + e.finalize()
    return ct, e.tag

lens = [(0, 0), (0, 1), (1, 0), (16, 16), (15, 17), (13, 0), (0, 48), (20, 200), (64, 257), (3, 1000)]
cases, data = [], bytearray()
for i in range(N):
    alen, tlen = lens[i] if i < len(lens) else (rng.choice([0, rng.randrange(1, 70)]), rng.randrange(0, 300))
    k256 = rng.randrange(2) if i >= 4 else i % 2
    dec = rng.randrange(2) if i >= 4 else 0
    key = bytes(rng.randrange(256) for _ in range(32 if k256 else 16))
    iv = bytes(rng.randrange(256) for _ in range(12))
    aad = bytes(rng.randrange(256) for _ in range(alen))
    pt = bytes(rng.randrange(256) for _ in range(tlen))
    ct, tag = gcm(key, iv, aad, pt)
    tl, ok = 0, 1
    if dec:
        kind = rng.randrange(3)
        if kind == 1: tl = rng.randrange(4, 16)
        if kind == 2:
            b = rng.randrange(16 if tl == 0 else tl)
            tag = tag[:b] + bytes([tag[b] ^ (1 << rng.randrange(8))]) + tag[b + 1:]
            ok = 0
        inp, outp = ct, pt
    else:
        inp, outp = pt, ct
    off = len(data)
    data += aad + inp + outp
    cases.append((k256, dec, ok, tl, alen, tlen, off, key.ljust(32, b"\0"), iv, tag))

o = []
a = o.append
a("// SPDX-License-Identifier: Apache-2.0")
a("// generated by scripts/crypto_dma/gen_vec.py: do not edit")
a(f"// {N} random AES-GCM messages, expected values from Python cryptography (OpenSSL)")
a(f"localparam int NV = {N};")
a(f"localparam int ND = {len(data)};")
a("logic [7:0]   vd [0:ND-1];               // per case: AAD, input text, expected output text")
a("logic [255:0] v_key [0:NV-1];")
a("logic [95:0]  v_iv [0:NV-1];")
a("logic [127:0] v_tag [0:NV-1];            // encrypt: expected tag; decrypt: TAG_IN")
a("logic [3:0]   v_tlen [0:NV-1];")
a("logic         v_k256 [0:NV-1], v_dec [0:NV-1], v_ok [0:NV-1];")
a("int           v_alen [0:NV-1], v_plen [0:NV-1], v_off [0:NV-1];")
a("task automatic load_vecs();")
for i, (k256, dec, ok, tl, alen, tlen, off, key, iv, tag) in enumerate(cases):
    a(f"  v_k256[{i}] = {k256}; v_dec[{i}] = {dec}; v_ok[{i}] = {ok}; v_tlen[{i}] = {tl}; "
      f"v_alen[{i}] = {alen}; v_plen[{i}] = {tlen}; v_off[{i}] = {off};")
    a(f"  v_key[{i}] = 256'h{key.hex()}; v_iv[{i}] = 96'h{iv.hex()}; v_tag[{i}] = 128'h{tag.hex()};")
for j in range(0, len(data), 16):
    a("  " + " ".join(f"vd[{j + k}] = 8'h{data[j + k]:02x};" for k in range(min(16, len(data) - j))))
a("endtask")
open(os.path.join(ROOT, "tb", "Crypto_DMA_vec.svh"), "w").write("\n".join(o) + "\n")
print(f"tb/Crypto_DMA_vec.svh: {N} cases, {len(data)} bytes")

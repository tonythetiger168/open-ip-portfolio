"""Generate tb/cov/<P>_fsm_cov.sv: FSM state + arc cover properties for every
FSM that fsm_extract.py finds in the protocol's RTL, bound into the DUT.

Cover-point naming (parsed by score.py):
  fsm_st__<var>__<STATE>            state visited
  fsm_arc__<var>__<FROM>__<TO>      explicit RTL transition taken
                                    (FROM = ANY for arcs written outside a
                                    state dispatch: "entered TO")
Usage: gen_fsm_cov.py <PROTOCOL> [--check]   (--check: exit 1 if stale)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fsm_extract

HDR = """// SPDX-License-Identifier: Apache-2.0
// AUTO-GENERATED by scripts/cov/gen_fsm_cov.py from the RTL -- do not edit.
// FSM state and transition (arc) coverage for {p}: one cover property per
// state and per explicit RTL arc, bound into the DUT module(s).
"""

def sv_ident(s):
    return s.replace("[", "_").replace("]", "_")

def gen(proto):
    top, mods = fsm_extract.extract(proto)
    out = [HDR.format(p=proto)]
    total = 0
    for mod, fsms in mods.items():
        if not fsms:
            continue
        cm = f"{mod}__fsm_cov"
        ports, conns, body = [], [], []
        clks = {}
        for f in fsms:
            v, w = f["var"], f["width"]
            clk = f["clock"][0]
            ce = "posedge" if f["clock"][1] == "PosEdge" else "negedge"
            if clk not in clks:
                clks[clk] = f"c_{clk}"
                ports.append(f"input logic c_{clk}")
                conns.append(f".c_{clk}({clk})")
            dis = "1'b0"
            if f["reset"]:
                r = f["reset"][0]
                if f"r_{r}" not in [p.split()[-1] for p in ports]:
                    ports.append(f"input logic r_{r}")
                    conns.append(f".r_{r}({r})")
                dis = f"!r_{r}" if f["reset"][1] == "NegEdge" else f"r_{r}"
            ports.append(f"input logic [{w-1}:0] s_{v}")
            conns.append(f".s_{v}({v})")
            ev = f"@({ce} c_{clk}) disable iff ({dis})"
            name = {val: n for n, val in f["states"].items()}
            body.append(f"  // ---- FSM {mod}.{v}: {len(f['states'])} states, "
                        f"{len(f['arcs'])} arcs ----")
            for n, val in f["states"].items():
                body.append(f"  fsm_st__{v}__{n}: cover property ({ev} s_{v} == {w}'d{val});")
                total += 1
            for a, b in f["arcs"]:
                if a == "*":
                    body.append(f"  fsm_arc__{v}__ANY__{name[b]}: cover property ({ev} "
                                f"s_{v} != {w}'d{b} ##1 s_{v} == {w}'d{b});")
                else:
                    body.append(f"  fsm_arc__{v}__{name[a]}__{name[b]}: cover property ({ev} "
                                f"s_{v} == {w}'d{a} ##1 s_{v} == {w}'d{b});")
                total += 1
        out.append(f"module {cm} (\n  " + ",\n  ".join(ports) + "\n);")
        out += body
        out.append("endmodule\n")
        out.append(f"bind {mod} {cm} u_fsm_cov (" + ", ".join(conns) + ");\n")
    if total == 0:
        out.append("// no clocked enum-typed state register found: FSM coverage N/A\n")
    return "\n".join(out), total

if __name__ == "__main__":
    p = sys.argv[1]
    text, n = gen(p)
    path = f"tb/cov/{p}_fsm_cov.sv"
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(path) and open(path).read() == text else 1)
    os.makedirs("tb/cov", exist_ok=True)
    open(path, "w").write(text)
    print(f"{path}: {n} FSM cover points")

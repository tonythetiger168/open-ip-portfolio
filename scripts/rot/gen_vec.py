"""Test cases for tb/Root_of_Trust_tb.sv, computed with Python's hashlib and
hmac (independent of the RTL and of the checker's SHA-256):
  python3 scripts/rot/gen_vec.py > tb/Root_of_Trust_vec.svh
Each boot case is one call of the TB task boot_case(): the OTP contents that
matter (lifecycle, scrap, anti-rollback, UDS, digest), the image (version
word, then words from a xorshift32 stream), and the expected result (boot
accepted, key). The image digest in the OTP is the image's SHA-256, or that
with one bit flipped (in the first, the last or a middle word) for a
rejected case.
"""
import hashlib, hmac, random

LC = {'RAW': 0, 'TEST': 0xFF, 'DEV': 0xFFFF, 'PROD': 0xFF00FF, 'RMA': 0xFFFFFFFF}
TOKENS = {'raw': b'RAW_UNLOCK_TOKEN', 'test': bytes.fromhex('00112233445566778899aabbccddeeff'),
          'rma': bytes.fromhex('f0e1d2c3b4a5968778695a4b3c2d1e0f')}


def xs32(x):
    x ^= (x << 13) & 0xFFFFFFFF
    x ^= x >> 17
    x ^= (x << 5) & 0xFFFFFFFF
    return x


def image(ver, n, seed):
    w, x = [ver], seed
    for _ in range(n - 1):
        x = xs32(x)
        w.append(x)
    return w


def h(b):
    return hashlib.sha256(b).digest()


def hx(b):
    return b.hex()


K256 = [int((p ** (1 / 3) % 1) * 2 ** 32) for p in [q for q in range(2, 312) if all(q % d for d in range(2, q))][:64]]


def sha256_blocks(msg):
    """SHA-256 compression over msg (a multiple of 64 bytes) as is: no padding
    added, so a block with any length field can be hashed."""
    ror = lambda x, n: (x >> n | x << (32 - n)) & 0xFFFFFFFF
    hs = [int((p ** 0.5 % 1) * 2 ** 32) for p in (2, 3, 5, 7, 11, 13, 17, 19)]
    for o in range(0, len(msg), 64):
        w = [int.from_bytes(msg[o + 4 * i:o + 4 * i + 4], 'big') for i in range(16)]
        for i in range(16, 64):
            s0 = ror(w[i - 15], 7) ^ ror(w[i - 15], 18) ^ w[i - 15] >> 3
            s1 = ror(w[i - 2], 17) ^ ror(w[i - 2], 19) ^ w[i - 2] >> 10
            w.append((w[i - 16] + s0 + w[i - 7] + s1) & 0xFFFFFFFF)
        a, b, c, d, e, f, g, hh = hs
        for i in range(64):
            t1 = hh + (ror(e, 6) ^ ror(e, 11) ^ ror(e, 25)) + (e & f ^ ~e & g) + K256[i] + w[i]
            t2 = (ror(a, 2) ^ ror(a, 13) ^ ror(a, 22)) + (a & b ^ a & c ^ b & c)
            a, b, c, d, e, f, g, hh = (t1 + t2) & 0xFFFFFFFF, a, b, c, (d + t1) & 0xFFFFFFFF, e, f, g
        hs = [(x + y) & 0xFFFFFFFF for x, y in zip(hs, (a, b, c, d, e, f, g, hh))]
    return b''.join(x.to_bytes(4, 'big') for x in hs)


rng = random.Random(7)
print("// SPDX-License-Identifier: Apache-2.0")
print('// generated by scripts/rot/gen_vec.py: do not edit')
print('// token hashes (SHA-256 of the tokens)')
for k in ('test', 'rma'):
    print(f"localparam logic [127:0] TOK_{k.upper()} = 128'h{hx(TOKENS[k])};")
    print(f"localparam logic [255:0] TOKH_{k.upper()} = 256'h{hx(h(TOKENS[k]))};")
print(f"localparam logic [127:0] TOK_RAW = 128'h{hx(TOKENS['raw'])};")
# one more image (version 0, 40 words) for the tamper and reset tests
w = image(0, 40, 0x12345679)
print(f"localparam logic [255:0] IMG_E_DIG = 256'h{hx(h(b''.join(x.to_bytes(4, 'big') for x in w)))};")
# an image of 2^14 words: a 14-bit word counter wraps to 0. IMG_WRAP_DIG is the
# digest with a length field of 0, what a core without the overflow flag would
# compute: a boot must still be refused with it in the OTP
w = b''.join(x.to_bytes(4, 'big') for x in image(0, 1 << 14, 1))
assert sha256_blocks(w + b'\x80' + bytes(55) + (len(w) * 8).to_bytes(8, 'big')) == h(w)
print(f"localparam logic [255:0] IMG_WRAP_DIG = 256'h{hx(sha256_blocks(w + b'\x80' + bytes(63)))};")
print('`ifndef ROT_VEC_CONSTS_ONLY  // the APB TB only takes the constants')
print('task automatic boot_cases();')
cases = []
# image lengths around every padding case (the last block holding 0..15 words), longer images
lens = list(range(1, 35)) + [47, 48, 49, 63, 64, 65, 100, 257]
for i, n in enumerate(lens):
    st = 'DEV' if i % 2 else 'PROD'
    arb = (1 << rng.randrange(0, 6)) - 1
    ver = bin(arb).count('1') + rng.randrange(0, 3)
    cases.append((st, arb, ver, n, 'good'))
cases += [('PROD', 0x7, 2, 20, 'rollback'), ('DEV', 0xFFFFFFFF, 31, 9, 'rollback'),
          ('DEV', 0xFFFFFFFF, 32, 9, 'good'), ('PROD', 0, 0, 30, 'baddig'), ('DEV', 1, 1, 16, 'baddig'),
          ('PROD', 0x3, 7, 1, 'baddig'), ('DEV', 0xFF, 8, 5, 'good'), ('PROD', 0xFFFFFF, 30, 6, 'good'),
          ('PROD', 0xFFFF, 0xFFFFFFFF, 7, 'good'), ('DEV', 0xFFFFFF, 23, 8, 'rollback')]
nbad = 0
for st, arb, ver, n, kind in cases:
    seed = rng.getrandbits(32) | 1
    uds = bytes(rng.getrandbits(8) for _ in range(32))
    words = image(ver, n, seed)
    msg = b''.join(w.to_bytes(4, 'big') for w in words)
    dig = h(msg)
    otp_dig = bytearray(dig)
    if kind == 'baddig':
        b = rng.randrange(256)
        b = (5, 250, 130)[nbad]          # one bit in the first, the last, a middle digest word
        nbad += 1
        otp_dig[b // 8] ^= 0x80 >> (b % 8)
    ok = kind == 'good'
    lcw = LC[st]
    key = hmac.new(uds, dig + lcw.to_bytes(4, 'big'), hashlib.sha256).digest() if ok else bytes(32)
    print(f"  boot_case(32'h{lcw:08x}, 32'h{arb:08x}, 256'h{hx(uds)}, 256'h{hx(bytes(otp_dig))}, "
          f"32'd{ver}, {n}, 32'h{seed:08x}, 1'b{int(ok)}, 256'h{hx(key)});")
print('endtask')
print('`endif')

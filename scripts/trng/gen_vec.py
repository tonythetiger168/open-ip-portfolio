"""Known-answer vectors for tb/TRNG_tb.sv, computed with Python's hashlib.

  python3 scripts/trng/gen_vec.py > tb/TRNG_vec.svh

The TRNG conditioner hashes 512 * n raw bits (n = 1..4, first bit as the MSB
of the first byte) with SHA-256. Each vector is such a bit string and its
digest; the testbench checks its own SHA-256 against them before it uses it
to predict the seeds, so the expected seeds trace back to hashlib.
"""
import hashlib, random

rnd = random.Random(0x7123)
cases = []
for n in (1, 2, 3, 4):
    for pat in ("rand", "zero", "ones"):
        nb = 64 * n
        if pat == "rand":
            m = bytes(rnd.getrandbits(8) for _ in range(nb))
        elif pat == "zero":
            m = bytes(nb)
        else:
            m = b"\xff" * nb
        cases.append((n, m, hashlib.sha256(m).digest()))

print("// SPDX-License-Identifier: Apache-2.0")
print("// generated by scripts/trng/gen_vec.py (hashlib): do not edit")
print("// SHA-256 of 512 * n bit strings; the string is in the low 512 * n bits, its first bit at the top")
print(f"localparam int NKAT = {len(cases)};")
for name, w, f in (("kat_n", 3, lambda c: f"3'd{c[0]}"), ("kat_msg", 2048, lambda c: f"2048'h{c[1].hex()}"),
                   ("kat_dig", 256, lambda c: f"256'h{c[2].hex()}")):
    print(f"function automatic logic [{w - 1}:0] {name}(input int i);")
    print("  case (i)")
    for k, c in enumerate(cases):
        print(f"    {k}: {name} = {f(c)};")
    print(f"    default: {name} = '0;")
    print("  endcase")
    print("endfunction")

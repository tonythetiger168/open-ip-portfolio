"""Known-answer cases for tb/PCIe_CXL_IDE_tb.sv.

  python3 scripts/ide/gen_vec.py > tb/PCIe_CXL_IDE_vec.svh

The TB runs the cases in order on a core with NS = 2 streams and CTR_W = 4.
A case with prog = 1 first sets the stream's configuration (Stream ID, IV
fixed field, type, epoch length), loads its key into every sub-stream slot
of key set ks in both directions (counters back to 1) and makes that set
active with km_go; otherwise the stream keeps its active set and the
counters run on. The model below follows the same sequence, so the IV of
each message (fixed field || slot counter) is known. Each case is a TLP
(header and payload of the given lengths) or a cachemem epoch of agg + 1
flits of 64 bytes; the expected transmit output (prefix, ciphertext, MAC)
comes from scripts/ide/ide_ref.py and is checked against Python's
cryptography package. The TB then feeds the protected message back to the
receive side and expects the original header and payload with a good MAC.
"""
import os, random, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ide_ref
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

CTR_MAX = 15                            # CTR_W = 4: all ones is never used


def blocks(b):
    return [b[i:i + 16] for i in range(0, len(b), 16)]


def main():
    rnd = random.Random(0x1DE)
    cases, pool = [], []
    act = {}                            # stream -> active key set
    ctr = {}                            # (stream, ks, sub) -> next counter
    cfg = {}                            # stream -> (id, fix, cm, agg, key)
    plan = []
    # TLPs on both streams with header / payload length sweeps, key refreshes,
    # then cachemem epochs of 1..4 flits on stream 1
    for i in range(56):
        plan.append(("tlp", i % 2))
    for i in range(8):
        plan.append(("cm", 1))
    for i in range(8):
        plan.append(("tlp", i % 2))
    hlens = [12, 16, 20, 32, 4, 8, 28, 13, 17, 30]
    plens = [0, 4, 16, 64, 128, 1, 15, 17, 33, 48, 100, 160, 255, 8]
    last_cm = {}
    for n, (kind, s) in enumerate(plan):
        cm = kind == "cm"
        prog = s not in act or rnd.random() < 0.3 or last_cm.get(s) != cm
        if not prog:
            ks0 = act[s]
            if any(ctr[(s, ks0, sub)] >= CTR_MAX - 1 for sub in range(3)):
                prog = True
        if prog:
            ks = 1 - act.get(s, 1)      # the other set: a key refresh
            key = bytes(rnd.getrandbits(8) for _ in range(32))
            fix = rnd.getrandbits(32)
            sid = rnd.getrandbits(8)
            agg = rnd.randrange(4) if cm else 0
            if n == 0:
                key = bytes(32); fix = 0; sid = 0
            if n == 1:
                key = b"\xff" * 32; fix = 0xFFFFFFFF; sid = 0xFF
            cfg[s] = (sid, fix, cm, agg, key)
            act[s] = ks
            for sub in range(3):
                ctr[(s, ks, sub)] = 1
            last_cm[s] = cm
        sid, fix, cm_, agg, key = cfg[s]
        ks = act[s]
        sub = 0 if cm else rnd.randrange(3)
        c = ctr[(s, ks, sub)]
        assert c < CTR_MAX
        ctr[(s, ks, sub)] = c + 1
        ib = len(pool)
        if cm:
            flits = bytes(rnd.getrandbits(8) for _ in range(64 * (agg + 1)))
            ct, mac = ide_ref.protect_epoch(key, fix, c, flits)
            assert AESGCM(key).encrypt(ide_ref.iv(fix, c), flits, b"")[:-4][-12:] == mac
            pfx, nh, hb, np_, pb = 0, 0, 0, len(flits) // 16, 16
            pool += blocks(flits)
        else:
            hl = hlens[n % len(hlens)]
            pl = plens[(n * 7) % len(plens)]
            hdr = bytes(rnd.getrandbits(8) for _ in range(hl))
            pay = bytes(rnd.getrandbits(8) for _ in range(pl))
            pfx, ct, mac = ide_ref.protect_tlp(key, fix, c, sid, ks, sub, hdr, pay)
            ref = AESGCM(key).encrypt(ide_ref.iv(fix, c), pay, pfx.to_bytes(4, "big") + hdr)
            assert ref[:-16] == ct and ref[-16:-4] == mac
            nh, hb = (hl + 15) // 16, (hl - 1) % 16 + 1
            np_, pb = (pl + 15) // 16, (pl - 1) % 16 + 1 if pl else 0
            pool += blocks(hdr) + blocks(pay)
        ob = len(pool)
        pool += blocks(ct)
        cases.append(dict(cm=int(cm), s=s, id=sid, ks=ks, sub=sub, fix=fix, key=key.hex(), prog=int(prog),
                          agg=agg, nh=nh, hb=hb, np=np_, pb=pb, ib=ib, ob=ob, pfx=pfx, mac=mac.hex()))
    w = sys.stdout.write
    w("// SPDX-License-Identifier: Apache-2.0\n")
    w("// generated by scripts/ide/gen_vec.py: do not edit\n")
    w(f"// {len(cases)} known-answer cases (TLPs and cachemem epochs), checked against Python's cryptography\n")
    w(f"localparam int NC = {len(cases)};\n")
    w(f"localparam int NBK = {len(pool)};\n")
    w("logic [127:0] vb [0:NBK-1];             // input blocks (header, payload / flits), expected ciphertext\n")
    w("logic [255:0] c_key [0:NC-1];\n")
    w("logic [31:0]  c_fix [0:NC-1], c_pfx [0:NC-1];\n")
    w("logic [95:0]  c_mac [0:NC-1];\n")
    w("logic [7:0]   c_id [0:NC-1];\n")
    w("int           c_cm [0:NC-1], c_s [0:NC-1], c_ks [0:NC-1], c_sub [0:NC-1], c_prog [0:NC-1], c_agg [0:NC-1];\n")
    w("int           c_nh [0:NC-1], c_hb [0:NC-1], c_np [0:NC-1], c_pb [0:NC-1], c_ib [0:NC-1], c_ob [0:NC-1];\n")
    w("task automatic vcase(input int i, input int cm, s, ks, sub, prog, agg, nh, hb, np, pb, ib, ob,\n"
      "                     input logic [7:0] id, input logic [31:0] fix, pfx, input logic [255:0] key,\n"
      "                     input logic [95:0] mac);\n")
    w("  c_cm[i] = cm; c_s[i] = s; c_ks[i] = ks; c_sub[i] = sub; c_prog[i] = prog; c_agg[i] = agg;\n")
    w("  c_nh[i] = nh; c_hb[i] = hb; c_np[i] = np; c_pb[i] = pb; c_ib[i] = ib; c_ob[i] = ob;\n")
    w("  c_id[i] = id; c_fix[i] = fix; c_pfx[i] = pfx; c_key[i] = key; c_mac[i] = mac;\n")
    w("endtask\n")
    w("task automatic load_vecs();\n")
    for i, b in enumerate(pool):
        w(f"  vb[{i}] = 128'h{(b + bytes(16 - len(b))).hex()};\n")
    for i, c in enumerate(cases):
        w(f"  vcase({i}, {c['cm']}, {c['s']}, {c['ks']}, {c['sub']}, {c['prog']}, {c['agg']}, {c['nh']}, {c['hb']}, "
          f"{c['np']}, {c['pb']}, {c['ib']}, {c['ob']}, 8'h{c['id']:02x}, 32'h{c['fix']:08x}, 32'h{c['pfx']:08x}, "
          f"256'h{c['key']}, 96'h{c['mac']});\n")
    w("endtask\n")


if __name__ == "__main__":
    main()

"""Test vectors for Ethernet_PCS (AMP = 3 pairs per marker period) from the
reference model pcs_ref.py:

  python3 scripts/ethpcs/gen_vec.py tb     # tb/Ethernet_PCS_vec.svh, _g.hex, _b.hex

_g.hex holds groups (264 bits, 66 hex digits a line), _b.hex beats (640
bits, 160 hex digits a line); the .svh gives the counts and the expected
event totals.
  TX: 9 pairs from reset (tx_am_sf = 5): random groups with 0..100 %
      control blocks and some invalid sync headers -> the 17 beats a pair.
  RX: a separate stream into the receiver, starting in the middle of a
      marker period (nothing comes out until the first marker group), with
      correctable errors (1..15 symbols a codeword), an uncorrectable pair,
      an uncorrectable marker pair (no miss), invalid transcoded blocks
      (header 0 with all flags 1; an unknown first block type), a marker
      group off its period, then three missing groups (one of them with
      only the first marker block damaged; the lock drops) and a relock -> the expected groups out and event counts.
"""
import os, random, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pcs_ref import AMBLK, NBLK, Rx, Tx, rnd_group  # noqa: E402

AMP = 3
rng = random.Random(2026)


def groups(n, p_ctrl=None, p_bad=0.0):
    return [rnd_group(rng, rng.random() if p_ctrl is None else p_ctrl, p_bad) for _ in range(n)]


def beats(syms):
    return [sum(s << (10 * i) for i, s in enumerate(syms[64 * b:64 * b + 64])) for b in range(17)]


def corrupt(syms, na, nb):
    """na / nb symbol errors in codeword A / B (positions in transmit order)."""
    s = list(syms)
    for cw, n in ((0, na), (1, nb)):
        for pos in rng.sample(range(544), n):
            # codeword symbol pos is tx_out symbol 16k + 2j (+1) with pos = 8k + j
            k, j = divmod(pos, 8)
            idx = 16 * k + 2 * j + ((cw + k) % 2)
            s[idx] ^= rng.randrange(1, 1024)
    return s


G, B = [], []
# ---- TX
tx = Tx(AMP)
txg0 = len(G)
for p in range(9):
    n = NBLK - (AMBLK if tx.pc == 0 else 0)
    pc = [None, 0.0, 1.0, 0.5, None, None, 0.2, None, None][p]
    gs = groups(n, pc, 0.05 if p in (4, 7) else 0.0)
    G += gs
    B += beats(tx.pair(gs, sf=5))
n_txg, n_txb = len(G), len(B)

# ---- RX
src, rx = Tx(AMP), Rx(AMP)
rxb0, rxg0 = len(B), len(G)
exp_g, am_err, itb, bad_pairs = [], 0, 0, 0
plan = [
    # (marker group: None = by period, errors A, errors B, extra)
    (None, 0, 0, "skip"),        # pair 0 is not sent: the receiver starts mid-period
    (None, 3, 0, ""), (None, 0, 0, ""),
    (None, 0, 0, ""),            # first marker group: lock
    (None, 15, 15, ""), (None, 7, 1, "itb"),
    (None, 20, 0, ""),           # a marker pair, uncorrectable: no miss
    (None, 0, 30, ""),           # uncorrectable data pair
    (True, 0, 0, ""),            # a marker group off its period
    (False, 0, 0, ""),           # missing 1
    (None, 0, 0, ""), (None, 0, 0, ""),
    (False, 0, 0, ""),           # missing 2
    (None, 0, 0, ""), (None, 0, 0, ""),
    (None, 0, 0, ""),            # found again: back in step
    (None, 0, 0, ""), (None, 0, 0, ""),
    ("bad0", 0, 0, ""),          # missing 1: only the first marker block differs
    (None, 0, 0, ""), (None, 0, 0, ""),
    (False, 0, 0, ""),           # missing 2
    (None, 0, 0, ""), (None, 0, 0, ""),
    (False, 2, 2, ""),           # missing 3: lock lost
    (None, 0, 0, ""), (None, 0, 0, ""),
    (None, 0, 0, "itb"),         # relock
    (None, 1, 0, ""), (None, 0, 0, ""),
]
for am, ea, eb, extra in plan:
    has_am = (src.pc == 0) if am is None else am
    n = NBLK - (AMBLK if has_am else 0)
    gs = groups(n)
    if extra == "itb":
        gs[3] = ("raw", 0x1E)                                  # header 0, all flags 1
        gs[9] = ("raw", (0x3 << 5) | (0b1110 << 1))            # first control block type nibble 3
    syms = src.pair(gs, sf=rng.randrange(8), am=am)
    if extra == "skip":
        continue
    syms = corrupt(syms, ea, eb)
    out, ev = rx.pair(syms)
    B += beats(syms)
    exp_g += out
    am_err += ev["am_err"]
    itb += ev["itb"]
G += exp_g
n_rxb, n_rxg = len(B) - rxb0, len(G) - rxg0

out = sys.argv[1] if len(sys.argv) > 1 else "tb"
with open(os.path.join(out, "Ethernet_PCS_g.hex"), "w") as f:
    f.writelines(f"{g:066x}\n" if isinstance(g, int) else
                 f"{sum(b << (66 * j) for j, b in enumerate(g)):066x}\n" for g in G)
with open(os.path.join(out, "Ethernet_PCS_b.hex"), "w") as f:
    f.writelines(f"{b:0160x}\n" for b in B)
with open(os.path.join(out, "Ethernet_PCS_vec.svh"), "w") as f:
    f.write("// generated by scripts/ethpcs/gen_vec.py: do not edit\n")
    for k, v in (("N_TXG", n_txg), ("N_TXB", n_txb), ("RX_B0", rxb0), ("N_RXB", n_rxb), ("RX_G0", rxg0),
                 ("N_RXG", n_rxg), ("RX_AM_ERR", am_err), ("RX_ITB", itb), ("RX_LOCK", int(rx.lock)),
                 ("RX_SF", rx.sf)):
        f.write(f"localparam int {k} = {v};\n")
print(f"TX {n_txg} groups / {n_txb} beats, RX {n_rxb} beats / {n_rxg} groups, am_err {am_err}, itb {itb}, "
      f"lock {rx.lock}")

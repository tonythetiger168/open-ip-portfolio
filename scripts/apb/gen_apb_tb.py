"""TB, checker, synthesis script and doc page generators for gen_apb.py."""
import json, os, re

AW = 12
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

ACCESS = {"id": "RO", "irq_status": "W1C", "irq_enable": "RW", "flags": "RO",
          "scratch": "RW", "rw": "RW", "ro": "RO", "cmd": "WO (pulse)",
          "sin": "RW", "sout": "RO (pop)"}


def access(w):
    if w.kind == "bus":
        return {(True, True): "RW (core)", (True, False): "WO (core)", (False, True): "RO (core)"}[
            (w.bus_widx is not None, w.bus_ridx is not None)]
    return ACCESS[w.kind]


def buses(spec):
    return [r for r in spec["regs"] if r["kind"] == "bus"]


def bus_of(spec, w):
    return next(r for r in buses(spec) if r["name"] == w.reg)


def vb(w):
    return "" if w == 1 else f"[{w-1}:0]"


def wmask(w):
    return (1 << w.wb) - 1


def word_bits(w, NI):
    """Number of implemented bits of a word (reads above them return 0)."""
    if w.kind == "irq_status" or w.kind == "irq_enable":
        return NI
    if w.kind in ("id", "scratch"):
        return 32
    return w.wb


def dp(r):
    d = r["data"] if isinstance(r["data"], list) else [r["data"]]
    return ", ".join(f"`{x}`" for x in d)


def stream_regs(spec):
    return [r for r in spec["regs"] if r["kind"] in ("stream_in", "stream_out")]


def sw(words, name):
    return [w for w in words if w.reg == name and w.kind in ("sin", "sout")]


# ----------------------------------------------------------------------------- TB
def gen_tb(P, spec, core, words, irqb, flagb, pt):
    order, width, dirn, decl, params, header = core
    NW, NI = len(words), len(irqb)
    code = int(spec["code"], 0)
    maj, mnr = (int(x) for x in spec["version"].split("."))
    idv = (code << 16) | (maj << 8) | mnr
    half = spec.get("tb_clk_ns", 10) / 2
    L = []
    a = L.append
    a("// SPDX-License-Identifier: Apache-2.0")
    a(f"// Self-checking TB of {P}_apb (generated by scripts/apb/gen_apb.py; do not edit).")
    a("// Generic part: reset values, ID, scratch and RW registers with byte strobes,")
    a("// read-only writes ignored, unmapped and misaligned accesses (PSLVERR),")
    a("// back-to-back and idle-separated transfers, reset at the end.")
    a(f"// IP part: task ip_func() from tb/apb/{P}_apb_func.svh drives the core")
    a("// through the registers and its protocol pins. The bound checker")
    a(f"// tb/cov/{P}_apb_sva.sv checks every read and every core input on every clock.")
    a("`timescale 1ns/1ps")
    if os.path.exists(os.path.join(ROOT, "tb", "apb", f"{P}_apb_models.svh")):
        # separate modules the IP part instantiates (e.g. a card or device model)
        a(f"`include \"apb/{P}_apb_models.svh\"")
    a(f"module {P}_apb_tb;")
    a("  logic        PCLK = 0, PRESETN = 0, PSEL = 0, PENABLE = 0, PWRITE = 0;")
    a(f"  logic [{AW-1}:0] PADDR = 0;")
    a("  logic [31:0] PWDATA = 0;")
    a("  logic [3:0]  PSTRB = 0;")
    a("  wire  [31:0] PRDATA;")
    a("  wire         PREADY, PSLVERR, irq;")
    for p in pt:
        kind = "logic" if dirn[p] == "input" else "tri  " if dirn[p] == "inout" else "wire "
        a(f"  {kind} {vb(width[p]):<8} {p};")
    tp = spec.get("tb_params", {})
    pp = (" #(" + ", ".join(f".{k}({v})" for k, v in tp.items()) + ")") if tp else ""
    a(f"  {P}_apb{pp} dut (.*);")
    a(f"  always #{half:g} PCLK = ~PCLK;")
    a("")
    a(f"  localparam logic [31:0] ID_VALUE = 32'h{idv:08X};")
    for w in words:
        a(f"  localparam logic [{AW-1}:0] A_{w.name} = {AW}'h{w.off:03X};")
    for i, (n, _, _) in enumerate(irqb):
        a(f"  localparam int IRQ_{n} = {i};")
    for i, (n, _) in enumerate(flagb):
        a(f"  localparam int FLAG_{n} = {i};")
    a(f"  localparam logic [31:0] IRQ_ALL = 32'h{(1 << NI) - 1:X};")
    a("")
    a("  int errors = 0;")
    a("  function automatic void fail(input string m);")
    a("    errors++;")
    a("    $display(\"ERROR: %s @%0t\", m, $time);")
    a("  endfunction")
    a("  task automatic cycles(input int n); repeat (n) @(negedge PCLK); endtask")
    a("")
    a("  // one APB transfer; read data and PSLVERR land in rdv / rerr")
    a("  logic [31:0] rdv;")
    a("  logic        rerr;")
    a("  bit          no_idle = 0;   // 1: never insert idle cycles")
    a(f"  task automatic apb(input logic w, input logic [{AW-1}:0] a, input logic [31:0] d,")
    a("                    input logic [3:0] s);")
    a("    if (!no_idle) repeat ($urandom % 3) @(negedge PCLK);")
    a("    @(negedge PCLK);")
    a("    apb_now(w, a, d, s);")
    a("  endtask")
    a("  // same, setup phase starting at the current negedge (exact access timing)")
    a(f"  task automatic apb_now(input logic w, input logic [{AW-1}:0] a, input logic [31:0] d,")
    a("                        input logic [3:0] s);")
    a("    PSEL = 1; PENABLE = 0; PWRITE = w; PADDR = a;")
    a("    PWDATA = w ? d : $urandom; PSTRB = w ? s : 4'h0;")
    a("    @(negedge PCLK);")
    a("    PENABLE = 1;")
    a("    #1;")
    a("    if (PREADY !== 1'b1) fail(\"PREADY low in access phase\");")
    a("    rdv = PRDATA; rerr = PSLVERR;")
    a("    @(posedge PCLK);")
    a("    #1 PSEL = 0; PENABLE = 0;")
    a("  endtask")
    a(f"  task automatic wr(input logic [{AW-1}:0] a, input logic [31:0] d);")
    a("    apb(1, a, d, 4'hF);")
    a("    if (rerr) fail($sformatf(\"PSLVERR on write %h\", a));")
    a("  endtask")
    a(f"  task automatic wrs(input logic [{AW-1}:0] a, input logic [31:0] d, input logic [3:0] s);")
    a("    apb(1, a, d, s);")
    a("    if (rerr) fail($sformatf(\"PSLVERR on write %h\", a));")
    a("  endtask")
    a(f"  task automatic rd(input logic [{AW-1}:0] a);")
    a("    apb(0, a, 0, 0);")
    a("    if (rerr) fail($sformatf(\"PSLVERR on read %h\", a));")
    a("  endtask")
    a(f"  task automatic rd_exp(input logic [{AW-1}:0] a, input logic [31:0] e);")
    a("    rd(a);")
    a("    if (rdv !== e) fail($sformatf(\"read %h = %h, expected %h\", a, rdv, e));")
    a("  endtask")
    a("  // poll until (read & mask) == val, at most n reads")
    a(f"  task automatic poll(input logic [{AW-1}:0] a, input logic [31:0] mask, input logic [31:0] val,")
    a("                     input int n);")
    a("    int k;")
    a("    k = 0;")
    a("    rd(a);")
    a("    while ((rdv & mask) != val && k < n) begin rd(a); k++; end")
    a("    if ((rdv & mask) != val) fail($sformatf(\"poll %h timed out (%h)\", a, rdv));")
    a("  endtask")
    a(f"  task automatic bad(input logic w, input logic [{AW-1}:0] a);")
    a("    apb(w, a, $urandom, 4'hF);")
    a("    if (!rerr) fail($sformatf(\"no PSLVERR at %h\", a));")
    a("    if (!w && rdv !== 0) fail($sformatf(\"unmapped read %h returned %h\", a, rdv));")
    a("  endtask")
    a("  function automatic logic [31:0] merge(input logic [31:0] o, input logic [31:0] n,")
    a("                                        input logic [3:0] s);")
    a("    for (int b = 0; b < 4; b++) if (s[b]) o[8*b +: 8] = n[8*b +: 8];")
    a("    return o;")
    a("  endfunction")
    a("  // RW register: ones, zeros, random byte strobes; restores rst afterwards")
    a(f"  task automatic rw_test(input logic [{AW-1}:0] a, input logic [31:0] m, input logic [31:0] rst);")
    a("    logic [31:0] v, d;")
    a("    logic [3:0]  s;")
    a("    wr(a, 32'hFFFF_FFFF); rd_exp(a, m);")
    a("    wr(a, 32'h0);         rd_exp(a, 0);")
    a("    v = 0;")
    a("    for (int i = 0; i < 16; i++) begin")
    a("      d = $urandom; s = i[3:0];")
    a("      wrs(a, d, s); v = merge(v, d, s) & m;")
    a("      rd_exp(a, v);")
    a("    end")
    a("    wr(a, rst); rd_exp(a, rst);")
    a("  endtask")
    a("")
    a(f"  `include \"apb/{P}_apb_func.svh\"")
    a("")
    a("  task automatic check_reset_values;")
    a("    rd_exp(A_ID, ID_VALUE);")
    a("    rd_exp(A_IRQ_ENABLE, 0);")
    a("    rd_exp(A_SCRATCH, 0);")
    for w in words:
        if w.kind == "rw":
            a(f"    rd_exp(A_{w.name}, 32'h{w.reset():X});")
        if w.kind == "sin":
            a(f"    rd_exp(A_{w.name}, 0);")
        if w.kind == "cmd":
            a(f"    rd_exp(A_{w.name}, 0);                             // write-only: reads 0")
    a("  endtask")
    a("")
    a("  task automatic reg_tests;")
    a("    check_reset_values();")
    a("    wr(A_ID, ~ID_VALUE); rd_exp(A_ID, ID_VALUE);          // read-only: ignored")
    a("    wr(A_FLAGS, 32'hFFFF_FFFF);")
    a("    rw_test(A_SCRATCH, 32'hFFFF_FFFF, 0);")
    a("    rw_test(A_IRQ_ENABLE, IRQ_ALL, 0);")
    for w in words:
        if w.kind == "rw" and not next((r for r in spec["regs"] if r["name"] == w.reg), {}).get("no_rw_test"):
            a(f"    rw_test(A_{w.name}, 32'h{wmask(w):X}, 32'h{w.reset():X});")
        if w.kind in ("ro", "sout"):
            a(f"    wr(A_{w.name}, 32'hFFFF_FFFF);                     // read-only: ignored")
    a("    // unmapped and misaligned: PSLVERR, read data 0, no side effects")
    a("    wr(A_SCRATCH, 32'h5A5A_A5A5);")
    bads = [NW * 4, (1 << AW) - 4, 1, 2, 3, 0x11, 0x13]
    bads += [1 << k for k in range(2, AW) if (1 << k) >= NW * 4]
    for b in sorted(set(bads)):
        a(f"    bad(0, {AW}'h{b:03X}); bad(1, {AW}'h{b:03X});")
    a("    rd_exp(A_SCRATCH, 32'h5A5A_A5A5);")
    a("    no_idle = 1;                                            // back-to-back")
    a("    for (int i = 0; i < 4; i++) begin wr(A_SCRATCH, i); rd_exp(A_SCRATCH, i); end")
    a("    no_idle = 0;")
    a("    wr(A_SCRATCH, 0);")
    a("    wr(A_IRQ_STATUS, IRQ_ALL);")
    a("  endtask")
    a("")
    a("  initial begin")
    a("    cycles(3);")
    a("    PRESETN = 1;")
    a("    cycles(2);")
    a("    reg_tests();")
    a("    ip_func();")
    a("    PRESETN = 0;")
    a("    cycles(3);")
    a("    if (irq !== 0 || PRDATA !== 0) fail(\"outputs in reset\");")
    a("    PRESETN = 1;")
    a("    cycles(2);")
    a("    check_reset_values();")
    if spec.get("irq_at_reset"):
        # core events that fire as soon as reset ends (a continuously
        # transmitting core): allowed in IRQ_STATUS right after reset
        m = " | ".join(f"(1 << IRQ_{n})" for n in spec["irq_at_reset"])
        a("    rd(A_IRQ_STATUS);")
        a(f"    if ((rdv & ~({m})) !== 0) fail($sformatf(\"IRQ_STATUS %h after reset\", rdv));")
    else:
        a("    rd_exp(A_IRQ_STATUS, 0);")
    a(f"    if (errors == 0) $display(\"TEST PASSED: {P}_apb\");")
    a(f"    else $display(\"TEST FAILED: {P}_apb (%0d errors)\", errors);")
    a("    $finish;")
    a("  end")
    a("")
    a("  initial begin")
    a(f"    #{spec.get('tb_timeout', '20ms')};")
    a(f"    $display(\"TEST FAILED: {P}_apb (timeout)\");")
    a("    $finish;")
    a("  end")
    a("endmodule")
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------------- checker
def gen_sva(P, spec, core, words, irqb, flagb, pt):
    order, width, dirn, decl, params, header = core
    NW, NI = len(words), len(irqb)
    code = int(spec["code"], 0)
    maj, mnr = (int(x) for x in spec["version"].split("."))
    idv = (code << 16) | (maj << 8) | mnr
    cports = []
    for w in words:
        for f in w.fields:
            if f.port not in cports:
                cports.append(f.port)
    for r in stream_regs(spec):
        for k in ("valid", "ready"):
            if r.get(k) and r[k] not in cports:
                cports.append(r[k])
    for _, _, port in irqb:
        if port and port not in cports:
            cports.append(port)
    for r in buses(spec):
        for k in ("wen", "wdata", "ren", "rdata"):
            if r.get(k) and r[k] not in cports:
                cports.append(r[k])
    bus_wr = [i for i, w in enumerate(words) if w.kind == "bus" and w.bus_widx is not None]
    bus_rd = [i for i, w in enumerate(words) if w.kind == "bus" and w.bus_ridx is not None]
    L = []
    a = L.append
    a("// SPDX-License-Identifier: Apache-2.0")
    a(f"// {P}_apb checker (generated by scripts/apb/gen_apb.py; do not edit).")
    a("// Register model held as an array of words, updated from the APB pins and")
    a("// the core's outputs; it predicts PRDATA on every read, PSLVERR, PREADY, irq")
    a("// and every core input the wrapper drives. FC: every word read and written,")
    a("// every interrupt bit set / cleared / masked / raising irq, stream events,")
    a("// strobes, unmapped and misaligned accesses, back-to-back transfers.")
    a("`include \"cov_macros.svh\"")
    a(f"module {P}_apb_sva (")
    pl = ["input logic PCLK, PRESETN, PSEL, PENABLE, PWRITE",
          f"input logic [{AW-1}:0] PADDR", "input logic [31:0] PWDATA", "input logic [3:0] PSTRB",
          "input logic [31:0] PRDATA", "input logic PREADY, PSLVERR, irq"]
    pl += [f"input logic {vb(width[p])} c_{p}" for p in cports]
    a(",\n".join("  " + x for x in pl))
    a(");")
    a("  `COV_CLOCKING(PCLK, !PRESETN)")
    a("  wire        m_wr  = PSEL && PENABLE && PWRITE;")
    a("  wire        m_rd  = PSEL && PENABLE && !PWRITE;")
    a(f"  wire        m_map = PADDR[1:0] == 2'b00 && (PADDR >> 2) < {NW};")
    a(f"  wire [{AW-3}:0] m_idx = PADDR[{AW-1}:2];")
    a("  wire [31:0] m_be  = {{8{PSTRB[3]}}, {8{PSTRB[2]}}, {8{PSTRB[1]}}, {8{PSTRB[0]}}};")
    a(f"  logic [31:0] m_w [0:{NW-1}];          // model of every stored word")
    a(f"  logic [{NI-1}:0] m_set;                // interrupt bits set this clock")
    for w in words:
        if w.kind == "cmd":
            a(f"  logic [31:0] m_pulse_{w.name};")
    for r in stream_regs(spec):
        a(f"  logic m_state_{r['name']};          // full / valid pulse / available")
    a("")
    # interrupt set conditions
    a("  always_comb begin")
    a("    m_set = '0;")
    for i, (n, _, port) in enumerate(irqb):
        if port:
            a(f"    if (c_{port}) m_set[{i}] = 1'b1;")
    for r in stream_regs(spec):
        n = r["name"]
        ws = sw(words, n)
        last = words.index(ws[-1])
        idxs = " || ".join(f"m_idx == {words.index(w)}" for w in ws)
        names = [x for x, _, _ in irqb]
        if r["kind"] == "stream_in" and r.get("ready"):
            a(f"    if (m_state_{n} && c_{r['ready']}) m_set[{names.index(n + '_DONE')}] = 1'b1;")
            a(f"    if (m_wr && m_map && ({idxs}) && m_state_{n}) m_set[{names.index(n + '_OVF')}] = 1'b1;")
        elif r["kind"] == "stream_out":
            pop = f"(m_rd && m_map && m_idx == {last})"
            a(f"    if (c_{r['valid']} && !m_state_{n}) m_set[{names.index(n + '_AVAIL')}] = 1'b1;")
            a(f"    if (c_{r['valid']} && m_state_{n} && {pop}) m_set[{names.index(n + '_AVAIL')}] = 1'b1;")
            if not r.get("ready"):
                a(f"    if (c_{r['valid']} && m_state_{n} && !{pop}) m_set[{names.index(n + '_OVF')}] = 1'b1;")
    a("  end")
    a("")
    a("  always_ff @(posedge PCLK or negedge PRESETN) begin")
    a("    if (!PRESETN) begin")
    for i, w in enumerate(words):
        a(f"      m_w[{i}] <= 32'h{(w.reset() if w.kind == 'rw' else 0):X};")
    for w in words:
        if w.kind == "cmd":
            a(f"      m_pulse_{w.name} <= 0;")
    for r in stream_regs(spec):
        a(f"      m_state_{r['name']} <= 0;")
    a("    end else begin")
    a(f"      m_w[1] <= (m_w[1] & ~((m_wr && m_map && m_idx == 1) ? PWDATA & m_be : 0)) | 32'(m_set);")
    for i, w in enumerate(words):
        if w.kind in ("irq_enable", "scratch", "rw"):
            msk = (1 << word_bits(w, NI)) - 1 if word_bits(w, NI) < 32 else 0xFFFFFFFF
            a(f"      if (m_wr && m_map && m_idx == {i}) m_w[{i}] <= ((m_w[{i}] & ~m_be) | (PWDATA & m_be)) & 32'h{msk:X};")
        if w.kind == "cmd":
            a(f"      m_pulse_{w.name} <= (m_wr && m_map && m_idx == {i}) ? PWDATA & m_be & 32'h{wmask(w):X} : 0;")
    for r in stream_regs(spec):
        n = r["name"]
        ws = sw(words, n)
        last = words.index(ws[-1])
        if r["kind"] == "stream_in":
            gate = f" && !m_state_{n}" if r.get("ready") else ""
            for w in ws:
                i = words.index(w)
                a(f"      if (m_wr && m_map && m_idx == {i}{gate}) m_w[{i}] <= ((m_w[{i}] & ~m_be) | (PWDATA & m_be)) & 32'h{wmask(w):X};")
            if r.get("ready"):
                a(f"      if (m_wr && m_map && m_idx == {last} && !m_state_{n}) m_state_{n} <= 1;")
                a(f"      if (m_state_{n} && c_{r['ready']}) m_state_{n} <= 0;")
            else:
                a(f"      m_state_{n} <= m_wr && m_map && m_idx == {last};")
        else:
            pop = f"(m_rd && m_map && m_idx == {last})"
            a(f"      if (c_{r['valid']} && (!m_state_{n} || {pop})) begin")
            for w in ws:
                terms = []
                for f in w.fields:
                    src = f"c_{f.port}" if width[f.port] == 1 else f"c_{f.port}[{f.plo + f.w - 1}:{f.plo}]"
                    terms.append(f"(32'({src}) << {f.lo})")
                a(f"        m_w[{words.index(w)}] <= {' | '.join(terms)};")
            a(f"        m_state_{n} <= 1;")
            a(f"      end else if ({pop}) m_state_{n} <= 0;")
    a("    end")
    a("  end")
    a("")
    # expected read
    a(f"  function automatic logic [31:0] m_read(input logic [{AW-3}:0] i);")
    a("    case (i)")
    for i, w in enumerate(words):
        if w.kind == "id":
            v = f"32'h{idv:08X}"
        elif w.kind == "flags":
            bits = []
            for n, _ in flagb:
                st = n[:-5] if n.endswith("_FULL") else n[:-6]
                bits.append(f"m_state_{st}")
            v = "32'({" + ", ".join(reversed(bits)) + "})" if bits else "0"
        elif w.kind == "cmd":
            v = "0"
        elif w.kind == "bus":
            v = f"32'(c_{bus_of(spec, w)['rdata']})" if w.bus_ridx is not None else "0"
        elif w.kind == "ro":
            v = "0"
            terms = []
            for f in w.fields:
                src = f"c_{f.port}" if width[f.port] <= 32 else f"c_{f.port}[{f.plo + f.w - 1}:{f.plo}]"
                terms.append(f"(32'({src}) << {f.lo})")
            v = " | ".join(terms)
        else:
            v = f"m_w[{i}]"
        a(f"      {i}: return {v};")
    a("      default: return 0;")
    a("    endcase")
    a("  endfunction")
    a("")
    # reset expectations on core inputs
    rst_terms = ["PRDATA == 0", "!irq"]
    a("  // ---------------- assertions ----------------")
    a("  `SVA_INV(a_pready_zero_wait, PREADY == (PSEL && PENABLE))")
    if bus_wr:
        cond = " || ".join(f"m_idx == {i}" for i in bus_wr)
        a(f"  wire        m_bus_partial = PWRITE && PSTRB != 4'hF && m_map && ({cond});   // dropped with PSLVERR")
        a("  `SVA_IMP(a_pslverr_decode, PSEL && PENABLE, PSLVERR == (!m_map || m_bus_partial))")
    else:
        a("  `SVA_IMP(a_pslverr_decode, PSEL && PENABLE, PSLVERR == !m_map)")
    a("  `SVA_IMP(a_read_data, m_rd && m_map, PRDATA == m_read(m_idx))")
    a("  `SVA_IMP(a_unmapped_read_zero, m_rd && !m_map, PRDATA == 0)")
    a("  `SVA_IMP(a_prdata_zero_outside_read, !m_rd, PRDATA == 0)")
    a(f"  `SVA_INV(a_irq_pin, irq == |(m_w[1][{NI-1}:0] & m_w[2][{NI-1}:0]))")
    for i, w in enumerate(words):
        for f in w.fields:
            if w.kind == "rw":
                exp = f"m_w[{i}][{f.lo + f.w - 1}:{f.lo}]"
                rv = (w.reset() >> f.lo) & ((1 << f.w) - 1)
            elif w.kind == "cmd":
                exp = f"m_pulse_{w.name}[{f.lo}]"
                rv = 0
            elif w.kind == "sin":
                exp = f"m_w[{i}][{f.lo + f.w - 1}:{f.lo}]"
                rv = 0
            else:
                continue
            lhs = f"c_{f.port}" if width[f.port] <= 32 else f"c_{f.port}[{f.plo + f.w - 1}:{f.plo}]"
            tag = re.sub(r"\W", "_", f.name).strip("_")
            a(f"  `SVA_INV(a_core_{tag}, {lhs} == {exp})")
            rst_terms.append(f"{lhs} == {f.w}'h{rv:X}")
    for r in buses(spec):
        bw = [(i, w) for i, w in enumerate(words) if w.reg == r["name"] and w.kind == "bus"]
        if r.get("wen"):
            ws = [(i, w) for i, w in bw if w.bus_widx is not None]
            cond = " || ".join(f"m_idx == {i}" for i, _ in ws)
            a(f"  wire m_bus_wr_{r['name']} = m_wr && m_map && PSTRB == 4'hF && ({cond});")
            sel = "".join(f"m_idx == {i} ? {w.bus_widx} : " for i, w in ws) + "0"
            wd = width[r["wdata"]]
            a(f"  `SVA_INV(a_core_{r['wen']}, c_{r['wen']} == m_bus_wr_{r['name']})")
            a(f"  `SVA_IMP(a_core_{r['waddr']}_{r['wdata']}, m_bus_wr_{r['name']}, "
              f"int'(u_core.{r['waddr']}) == ({sel}) && c_{r['wdata']} == PWDATA[{wd - 1}:0])")
            rst_terms.append(f"!c_{r['wen']}")
        if r.get("ren") or r.get("raddr"):
            rs = [(i, w) for i, w in bw if w.bus_ridx is not None]
            cond = " || ".join(f"m_idx == {i}" for i, _ in rs)
            a(f"  wire m_bus_rd_{r['name']} = m_rd && m_map && ({cond});")
            sel = "".join(f"m_idx == {i} ? {w.bus_ridx} : " for i, w in rs) + "0"
            if r.get("ren"):
                a(f"  `SVA_INV(a_core_{r['ren']}, c_{r['ren']} == m_bus_rd_{r['name']})")
                rst_terms.append(f"!c_{r['ren']}")
            if r.get("raddr") and r["raddr"] == r.get("waddr"):
                a(f"  `SVA_IMP(a_core_{r['raddr']}_rd, m_bus_rd_{r['name']}, int'(u_core.{r['raddr']}) == ({sel}))")
            elif r.get("raddr"):
                a(f"  `SVA_INV(a_core_{r['raddr']}, int'(u_core.{r['raddr']}) == (m_bus_rd_{r['name']} ? ({sel}) : 0))")
    for r in stream_regs(spec):
        if r["kind"] == "stream_in":
            a(f"  `SVA_INV(a_core_{r['valid']}, c_{r['valid']} == m_state_{r['name']})")
            rst_terms.append(f"!c_{r['valid']}")
        elif r.get("ready"):
            last = words.index(sw(words, r["name"])[-1])
            a(f"  `SVA_INV(a_core_{r['ready']}, c_{r['ready']} == (!m_state_{r['name']} || (m_rd && m_map && m_idx == {last})))")
            rst_terms.append(f"c_{r['ready']}")
    a(f"  `SVA_RST(a_reset_values, !PRESETN, {' && '.join(rst_terms)})")
    a("")
    a("  // ---------------- functional coverage ----------------")
    for i, w in enumerate(words):
        a(f"  `FC(rd_{w.name}, m_rd && m_map && m_idx == {i})")
        a(f"  `FC(wr_{w.name}, m_wr && m_map && m_idx == {i})")
    a("  `FC(unmapped_read, m_rd && !m_map && PADDR[1:0] == 0)")
    a("  `FC(unmapped_write, m_wr && !m_map && PADDR[1:0] == 0)")
    a("  `FC(misaligned_read, m_rd && PADDR[1:0] != 0)")
    a("  `FC(misaligned_write, m_wr && PADDR[1:0] != 0)")
    a("  `FC(partial_strobe_write, m_wr && m_map && PSTRB != 4'h0 && PSTRB != 4'hF)")
    a("  `FC(zero_strobe_write, m_wr && m_map && PSTRB == 4'h0)")
    a("  `FC(back_to_back, PSEL && PENABLE ##1 PSEL && !PENABLE)")
    a("  `FC(idle_between, PSEL && PENABLE ##1 !PSEL)")
    for i, (n, _, _) in enumerate(irqb):
        a(f"  `FC(irq_{n}_set, m_set[{i}])")
        a(f"  `FC(irq_{n}_cleared, m_w[1][{i}] && m_wr && m_map && m_idx == 1 && PWDATA[{i}] && PSTRB[{i // 8}])")
        a(f"  `FC(irq_{n}_masked, m_w[1][{i}] && !m_w[2][{i}])")
        a(f"  `FC(irq_{n}_drives_pin, m_w[1][{i}] && m_w[2][{i}] && irq)")
    for w in words:
        if w.kind == "cmd":
            for f in w.fields:
                a(f"  `FC(cmd_{f.port}, m_pulse_{w.name}[{f.lo}])")
    for r in stream_regs(spec):
        n = r["name"]
        ws = sw(words, n)
        last = words.index(ws[-1])
        if r["kind"] == "stream_in" and r.get("ready"):
            a(f"  `FC({n}_handshake, m_state_{n} && c_{r['ready']})")
            a(f"  `FC({n}_backpressure, m_state_{n} && !c_{r['ready']})")
            a(f"  `FC({n}_write_while_full, m_wr && m_map && m_idx == {last} && m_state_{n})")
        elif r["kind"] == "stream_in":
            a(f"  `FC({n}_commit, m_state_{n})")
        else:
            a(f"  `FC({n}_capture, c_{r['valid']} && !m_state_{n})")
            if r.get("ready"):
                a(f"  `FC({n}_backpressure, c_{r['valid']} && m_state_{n} && !(m_rd && m_map && m_idx == {last}))")
            else:
                a(f"  `FC({n}_overflow, c_{r['valid']} && m_state_{n} && !(m_rd && m_map && m_idx == {last}))")
            a(f"  `FC({n}_pop, m_rd && m_map && m_idx == {last} && m_state_{n})")
            a(f"  `FC({n}_read_empty, m_rd && m_map && m_idx == {last} && !m_state_{n})")
            a(f"  `FC({n}_pop_and_capture, c_{r['valid']} && m_state_{n} && m_rd && m_map && m_idx == {last})")
    if bus_wr:
        a("  `FC(core_register_partial_write, m_wr && m_bus_partial)")
    a("  `FC_RST(reset_with_pending_irq, PRESETN && m_w[1] != 0 ##1 !PRESETN)")
    a("endmodule")
    a("")
    a(f"bind {P}_apb {P}_apb_sva u_apb_sva (.*);")
    return "\n".join(L) + "\n"



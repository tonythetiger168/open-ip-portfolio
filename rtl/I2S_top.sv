// I2S slave transmitter/receiver, 16-bit samples, 2 channels
// Samples SDIN on BCLK rise, shifts SDOUT on BCLK fall, with the I2S
// standard one-BCLK data delay after each LRCK transition.
// Clock ratio: BCLK is oversampled, so SDOUT changes up to two clk periods
// after a BCLK falling edge (synchroniser + edge detect). The I2S
// transmitter limit (data valid 0.8 T after the previous rising edge, so
// 0.3 T after the fall, leaving the receiver its 0.2 T setup) then needs
// 2 * Tclk + t_co(sdout pad) <= 0.3 * T_BCLK: clk >= 7 x BCLK, with 8 x or
// more recommended so the pad delay fits. SDIN is taken in the clk cycle
// after the BCLK rise, so the master must hold it one clk past the rise
// (a master that changes SDIN on the falling edge holds it T / 2).
// Auto-generated by gen_framework.py -- Apache-2.0
// ============================================================================
module I2S_top #(
  parameter int DW = 16
)(
  input  logic            clk,
  input  logic            rst_n,
  input  logic            bclk,
  input  logic            lrck,      // 0 = left, 1 = right
  input  logic            sdin,
  output logic            sdout,
  input  logic            wen,
  input  logic [3:0]      waddr,     // 0: tx_left, 1: tx_right
  input  logic [DW-1:0]   wdata,
  input  logic            ren,
  input  logic [3:0]      raddr,     // 0: rx_left, 1: rx_right
  output logic [DW-1:0]   rdata,
  output logic            irq        // frame-sync (LRCK change) pulse
);
  // Philips I2S timing: LRCK changes on a BCLK falling edge, and the MSB of
  // the new channel's word follows one BCLK later (on the next falling edge;
  // the master samples it on the second rising edge after the LRCK change).
  // A channel slot may be longer than DW bits: bits after the LSB are
  // padding (TX sends 0, RX ignores them).
  localparam int CW = $clog2(DW + 1);
  logic [DW-1:0] tx_left, tx_right, rx_left, rx_right;
  logic [DW-1:0] tx_shift;
  logic [DW-2:0] rx_shift;            // first DW-1 bits of the RX word
  logic [CW-1:0] rx_cnt;               // bits of the current RX word (DW = done)
  logic          tx_pend, tx_ch;       // load tx_ch's word on the next fall
  logic          rx_pend, rx_ch_n;     // start rx_ch_n's word after the next rise
  logic          rx_ch;
  logic          bclk_s, bclk_d, lrck_s, lrck_d, sdin_s;

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      bclk_s <= 1'b0; bclk_d <= 1'b0;
      lrck_s <= 1'b0; lrck_d <= 1'b0; sdin_s <= 1'b0;
    end else begin
      bclk_s <= bclk; bclk_d <= bclk_s;
      lrck_s <= lrck; lrck_d <= lrck_s;
      sdin_s <= sdin;                  // sampled with bclk_s: the bit at the edge
    end
  end
  wire bclk_rise   =  bclk_s & ~bclk_d;
  wire bclk_fall   = ~bclk_s &  bclk_d;
  wire lrck_change =  lrck_s ^  lrck_d;
  wire [DW-1:0] rx_word = {rx_shift, sdin_s};

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      tx_left <= '0; tx_right <= '0;
      tx_shift <= '0; tx_pend <= 1'b0; tx_ch <= 1'b0;
    end else begin
      if (wen && waddr == 4'd0) tx_left  <= wdata;
      if (wen && waddr == 4'd1) tx_right <= wdata;
      if (bclk_fall) begin
        if (tx_pend) begin
          tx_shift <= tx_ch ? tx_right : tx_left;   // MSB one BCLK after LRCK
          tx_pend  <= 1'b0;
        end else begin
          tx_shift <= {tx_shift[DW-2:0], 1'b0};
        end
      end
      if (lrck_change) begin tx_pend <= 1'b1; tx_ch <= lrck_s; end
    end
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      rx_left <= '0; rx_right <= '0; rx_shift <= '0;
      rx_cnt <= CW'(DW); rx_pend <= 1'b0; rx_ch_n <= 1'b0; rx_ch <= 1'b0;
    end else begin
      if (bclk_rise) begin
        // the first rise after an LRCK change still carries the previous
        // word's LSB when the slot is exactly DW bits
        if (rx_cnt != CW'(DW)) begin
          rx_shift <= rx_word[DW-2:0];
          rx_cnt   <= rx_cnt + 1'b1;
          if (rx_cnt == CW'(DW - 1)) begin
            if (!rx_ch) rx_left  <= rx_word;
            else        rx_right <= rx_word;
          end
        end
        if (rx_pend) begin rx_cnt <= '0; rx_ch <= rx_ch_n; rx_pend <= 1'b0; end
      end
      if (lrck_change) begin rx_pend <= 1'b1; rx_ch_n <= lrck_s; end
    end
  end

  assign sdout = tx_shift[DW-1];
  assign rdata = (raddr == 4'd0) ? rx_left :
                 (raddr == 4'd1) ? rx_right : '0;
  assign irq   = lrck_change;
  // ren is part of the common register-port shape; reads have no side effect
  wire _unused = &{1'b0, ren};

endmodule
